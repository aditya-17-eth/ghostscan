import assert from "node:assert/strict";
import { chromium } from "playwright";
import { readFile, mkdir, writeFile } from "node:fs/promises";

const base = process.env.TEST_URL ?? "http://127.0.0.1:4173";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, reducedMotion: "reduce" });
const page = await context.newPage();
const observedHostRpc = [];
const errors = [];
const checks = [];
const DEPOSIT = "0x00000000219ab540356cBB839Cbe05303d7705Fa";
const DEAD = "0x000000000000000000000000000000000000dEaD";
const WETH = "0xC02aaA39b223FE8D0A0e5C4F27eAD9083C756Cc2";
page.on("pageerror", e => errors.push(e.message));
page.on("request", req => {
  if (req.method() !== "POST") return;
  try { const body = JSON.parse(req.postData()); if (body.jsonrpc) observedHostRpc.push({ destination: new URL(req.url()).hostname, method: body.method, params: body.params }); }
  catch { /* network's own protocol */ }
});
const mark = text => { checks.push(text); console.log(`PASS ${text}`); };
let progress;
try {
  await mkdir("test-results", { recursive: true });
  await page.goto(base);
  await page.screenshot({ path: "test-results/overview-connecting.png", fullPage: true });
  assert.match(await page.getByTestId("status").innerText(), /ANON-RPC/);
  mark("Anon-RPC is the production default");
  progress = setInterval(() => console.log("Browser test awaiting real network/UI response…"), 20_000);
  await page.getByTestId("status").filter({ hasText: "ANON-RPC ACTIVE" }).waitFor({ timeout: 240_000 });
  mark("Real Nym worker connects in production export");
  await page.getByLabel("Ethereum address", { exact: true }).fill("invalid");
  await page.getByRole("button", { name: "Explore privately", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "Enter a valid" }).waitFor();
  assert.equal(observedHostRpc.filter(r => r.method === "eth_getBalance").length, 0);
  mark("Invalid addresses are rejected before RPC dispatch");
  await page.getByLabel("Ethereum address", { exact: true }).fill(DEPOSIT);
  await page.getByRole("button", { name: "Explore privately", exact: true }).click();
  await page.getByTestId("investigation-result").waitFor({ timeout: 120_000 });
  assert.match(await page.getByTestId("balance").innerText(), /\d.*ETH/);
  assert.match(await page.getByTestId("investigation-result").innerText(), /Smart contract/);
  assert.equal(observedHostRpc.filter(r => ["eth_getBalance", "eth_getCode", "eth_getTransactionCount", "eth_blockNumber"].includes(r.method)).length, 0);
  mark("Real balance, nonce, code and shared-block contract classification use worker; no host direct investigation RPC");
  await page.screenshot({ path: "test-results/explorer-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Contract Inspector", exact: true }).click();
  await page.getByLabel("Ethereum address", { exact: true }).fill(WETH);
  await page.getByRole("button", { name: "Explore privately", exact: true }).click();
  await page.getByTestId("investigation-result").waitFor({ timeout: 120_000 });
  assert.match(await page.getByTestId("investigation-result").innerText(), /Bytecode keccak256/);
  assert.match(await page.getByTestId("investigation-result").innerText(), new RegExp(WETH));
  mark("Contract inspector reads real WETH bytecode and hash");
  await page.getByRole("button", { name: "Address Explorer", exact: true }).click();
  await page.getByLabel("Ethereum address", { exact: true }).fill(DEAD);
  await page.getByRole("button", { name: "Explore privately", exact: true }).click();
  await page.getByTestId("investigation-result").waitFor({ timeout: 120_000 });
  assert.match(await page.getByTestId("investigation-result").innerText(), /No deployed code/);
  mark("Real no-code address classification does not infer ownership");
  await page.getByRole("button", { name: "Privacy Lab", exact: true }).click();
  await page.getByLabel("Address to compare").fill(DEPOSIT);
  await page.getByRole("button", { name: "Run comparison (also sends directly)", exact: true }).click();
  await page.getByText("Completed", { exact: true }).nth(1).waitFor({ timeout: 120_000 });
  const responses = await page.locator(".comparison-data > div:last-child dd").allTextContents();
  assert.equal(responses[0], responses[1]);
  assert.equal(observedHostRpc.filter(r => r.method === "eth_getBalance").length, 1);
  assert.match(await page.getByTestId("status").innerText(), /ANON-RPC ACTIVE/);
  mark("Explicit comparison returns equal real balances at the same block; one direct request; session stays anonymous mode");
  await page.screenshot({ path: "test-results/privacy-lab.png", fullPage: true });
  await page.getByRole("button", { name: "RPC Observatory", exact: true }).click();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export diagnostics", exact: true }).click();
  const download = await downloadPromise;
  const reportText = await readFile(await download.path(), "utf8");
  const report = JSON.parse(reportText);
  assert.equal(report.accounting.bootstrap, 3);
  assert.equal(report.accounting.direct, 1);
  assert.ok(report.accounting.coverage < 100);
  assert.equal(reportText.includes(DEPOSIT), false);
  assert.equal(reportText.includes(WETH), false);
  assert.equal(reportText.includes('"params"'), false);
  await writeFile("test-results/browser-diagnostic-export.json", reportText);
  mark("Observatory counts bootstrap and direct comparison; diagnostic export omits investigation contents");
  await page.getByLabel("Filter by transport").selectOption("bootstrap");
  assert.equal(await page.locator("tbody tr").count(), 3);
  await page.getByLabel("Filter by method").selectOption("eth_call");
  assert.equal(await page.locator("tbody tr").count(), 2);
  await page.getByRole("button", { name: "eth_call", exact: true }).first().click();
  await page.getByText(/sanitized details/).waitFor();
  mark("Transport and method filters and sanitized request inspection work");
  await page.getByRole("button", { name: "Clear history", exact: true }).click();
  const clearedDownloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export diagnostics", exact: true }).click();
  const clearedDownload = await clearedDownloadPromise;
  const clearedText = await readFile(await clearedDownload.path(), "utf8");
  const clearedReport = JSON.parse(clearedText);
  assert.deepEqual(clearedReport.accounting, report.accounting);
  assert.equal(clearedReport.events.length, 0);
  assert.equal(clearedReport.clearedDetailRows, 20);
  await writeFile("test-results/cleared-diagnostic-export.json", clearedText);
  mark("Clearing details preserves complete session totals and bootstrap coverage in UI/export");
  await page.getByLabel("Switch to direct RPC", { exact: true }).click();
  await page.getByRole("button", { name: "Keep Anon-RPC", exact: true }).focus();
  await page.keyboard.press("Shift+Tab");
  assert.equal(await page.getByRole("button", { name: "Enable direct RPC", exact: true }).evaluate(el => document.activeElement === el), true);
  await page.keyboard.press("Tab");
  assert.equal(await page.getByRole("button", { name: "Keep Anon-RPC", exact: true }).evaluate(el => document.activeElement === el), true);
  await page.getByRole("button", { name: "Keep Anon-RPC", exact: true }).click();
  assert.match(await page.getByTestId("status").innerText(), /ANON-RPC ACTIVE/);
  await page.getByLabel("Switch to direct RPC", { exact: true }).click();
  await page.getByRole("button", { name: "Enable direct RPC", exact: true }).click();
  assert.match(await page.getByTestId("status").innerText(), /DIRECT RPC MODE/);
  assert.match(await page.locator(".sidebar-network").innerText(), /Direct RPC mode/);
  await page.getByRole("button", { name: "Address Explorer", exact: true }).click();
  await page.getByLabel("Ethereum address", { exact: true }).fill(DEAD);
  await page.getByRole("button", { name: "Explore directly", exact: true }).click();
  await page.getByTestId("investigation-result").waitFor({ timeout: 30_000 });
  assert.equal(observedHostRpc.filter(r => r.method === "eth_getBalance").length, 2);
  mark("Direct mode requires confirmation and is visibly labeled; explicit direct explorer works");
  await page.getByLabel("Return to Anon-RPC", { exact: true }).click();
  await page.getByTestId("status").filter({ hasText: "ANON-RPC ACTIVE" }).waitFor({ timeout: 240_000 });
  mark("Reconnect closes direct mode and restores actual Nym readiness");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "test-results/explorer-mobile.png", fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByLabel("Toggle navigation").click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("heading", { name: "Choose who carries the query." }).waitFor();
  mark("390px mobile layout has no horizontal overflow and navigation works");
  assert.deepEqual(errors, []);
  await writeFile("test-results/browser-live.json", JSON.stringify({ testedAt: new Date().toISOString(), checks, comparisonResponses: responses, diagnosticAccounting: report.accounting, observedHostRpc, pageErrors: errors,
    scope: "Real production browser flow. Host request observation and application dispatch do not independently verify network-layer anonymity." }, null, 2));
  console.log(JSON.stringify({ checks, accounting: report.accounting }, null, 2));
} catch (e) {
  await page.screenshot({ path: "test-results/browser-failure.png", fullPage: true }).catch(() => {});
  console.error(e); process.exitCode = 1;
} finally { clearInterval(progress); await browser.close(); }
